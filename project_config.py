"""Resolves every path from Data/Data_Config/paths.yaml + Data/Sites/<site>/site.json.

Scripts use it like this:
    ROOT = Path(__file__).resolve().parents[2]
    sys.path.insert(0, str(ROOT))
    from project_config import load_config
    cfg = load_config()
"""
from pathlib import Path
import json
import yaml

ROOT = Path(__file__).resolve().parent


def load_config():
    paths = yaml.safe_load(open(ROOT / "Data" / "Data_Config" / "paths.yaml"))
    site, camera = paths["site"], paths["camera"]
    site_dir = ROOT / "Data" / "Sites" / site
    site_info = json.load(open(site_dir / "site.json"))
    cam_info = site_info.get("cameras", {}).get(camera, {})

    working_root = Path(paths["working_root"])
    dataset_root = working_root / site_info["dataset_root"]

    cfg = {
        "root": ROOT,
        "site": site,
        "camera": camera,
        "site_dir": site_dir,
        "calib_dir": site_dir / camera,  # this camera position's calibration files
        "crs": site_info["crs"],  # e.g. "EPSG:32632"
        "working_root": working_root,
        "dataset_root": dataset_root,
        "frames_dir": dataset_root / site_info["frames_subdir"].format(camera=camera),
        "calib_name": cam_info.get("calib_name"),
        "view_num": cam_info.get("view_num"),
        # per-camera, regenerated by the Detection scripts (git-ignored)
        "detections_dir": site_dir / camera / "detections",  # CSV / GeoJSON data
        "checks_dir": site_dir / camera / "checks",  # check images
    }
    cfg["calib_dir"].mkdir(parents=True, exist_ok=True)
    cfg["detections_dir"].mkdir(parents=True, exist_ok=True)
    cfg["checks_dir"].mkdir(parents=True, exist_ok=True)
    if not working_root.exists():
        print(f"[config] working drive not found: {working_root}")
    return cfg
